// Generate src/report/schema.ts from the report JSON Schema printed by `tarafold schema`.
// Usage: node scripts/gen-types.mjs [schema.json]
// Without an argument it runs `cargo run -q -p tarafold-cli -- schema` from the repo root.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const text = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : execFileSync("cargo", ["run", "-q", "-p", "tarafold-cli", "--", "schema"], {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    });
const schema = JSON.parse(text);
const ts = await compile(schema, "Report", {
  bannerComment:
    "/* Generated by scripts/gen-types.mjs from `tarafold schema`. Do not edit by hand. */",
  additionalProperties: false,
  style: { singleQuote: false },
});
writeFileSync(resolve(here, "..", "src", "report", "schema.ts"), ts);
console.log("wrote src/report/schema.ts");
